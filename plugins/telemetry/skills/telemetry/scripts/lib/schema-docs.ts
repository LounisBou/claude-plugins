// The index of the logs repository, generated from the declared kinds (hooks/schema.ts) and the
// manifest's fields (manifest.ts): an entry point, one page per event kind, the manifest's page and
// a machine-readable schema. Nothing here names a kind: a kind added to the list joins the index.
import { COMMON_FIELDS, EVENT_SCHEMA, type FieldSpec, type KindSpec } from '../../../../hooks/schema.ts'
import { MANIFEST_FIELDS } from './manifest.ts'

/** The directory of the index in the logs repository. */
export const INDEX_DIR = 'index'

/** A file of the index: its path in the repository and its text. */
export interface IndexFile {
  readonly path: string
  readonly text: string
}

const json = (value: unknown): string => `${JSON.stringify(value, null, 2)}\n`

function table(fields: readonly FieldSpec[]): string {
  const rows = fields.map(f => `| \`${f.name}\` | ${f.type} | ${f.unit ?? ''} | ${f.description} |`)
  return ['| Field | Type | Unit | Meaning |', '|---|---|---|---|', ...rows].join('\n')
}

function eventPage(kind: string, spec: KindSpec): string {
  return [
    `# ${kind}`,
    '',
    spec.summary,
    '',
    '## Written by',
    '',
    ...spec.writers.map(writer => `- ${writer}`),
    '',
    '## Fields',
    '',
    'Every line also carries the common fields: ' + COMMON_FIELDS.map(f => `\`${f.name}\``).join(', ') + ' (see `README.md`).',
    '',
    table(spec.fields),
    '',
  ].join('\n')
}

function entryPoint(kinds: Readonly<Record<string, KindSpec>>): string {
  return [
    '# Session logs index',
    '',
    'What this repository holds and how to read it without reading every line. Generated by the',
    'export of the `telemetry` plugin: edit nothing here.',
    '',
    '## Layout',
    '',
    '- `machines/<machine>/<day>.jsonl`: the events of one UTC day, one JSON object per line, redacted.',
    '- `machines/<machine>/transcripts/<session>.jsonl`: the raw transcript of a session the day files name, redacted by the export as the day files are (every secret replaced by `[REDACTED:<pattern>]`).',
    '- `index/<machine>/<day>.json`: that day\'s manifest (`schema/manifest.md`): its sessions with role and model, the pull requests, branches and dispatch rows its events name.',
    '- `index/schema/<event>.md`: one page per event kind; `index/schema.json` the same, machine-readable.',
    '',
    'Raw transcripts are in this repository, redacted: they hold prompts and may have held secrets. A',
    'session entry of a manifest names its transcript\'s path here, null when the recording machine no',
    'longer had the file.',
    '',
    '## Common fields',
    '',
    table(COMMON_FIELDS),
    '',
    '## Event kinds',
    '',
    ...Object.entries(kinds).map(([kind, spec]) => `- [\`${kind}\`](schema/${kind}.md): ${spec.summary}`),
    '',
  ].join('\n')
}

/** The files of the index for `kinds`: the declared list unless a caller passes another. */
export function schemaFiles(kinds: Readonly<Record<string, KindSpec>> = EVENT_SCHEMA): IndexFile[] {
  return [
    { path: `${INDEX_DIR}/README.md`, text: entryPoint(kinds) },
    ...Object.entries(kinds).map(([kind, spec]): IndexFile => ({ path: `${INDEX_DIR}/schema/${kind}.md`, text: eventPage(kind, spec) })),
    { path: `${INDEX_DIR}/schema/manifest.md`, text: ['# Day manifest', '', 'One per day file, at `index/<machine>/<day>.json`.', '', table(MANIFEST_FIELDS), ''].join('\n') },
    { path: `${INDEX_DIR}/schema.json`, text: json({ v: 1, common: COMMON_FIELDS, events: kinds, manifest: MANIFEST_FIELDS }) },
  ]
}
