// drift shots — whether two refs of a repository render the same pixels. Its command line, its
// lines and its exit codes are documented in the header of drift.sh.
//
// Each ref is checked out and installed like drift build's, at the same temporary path. Its server
// is started there (lib/server.ts), the capture spec run against it with the shared Playwright
// install, and the server stopped with its process group, on failure too, before the checkout is
// removed. Once both sides are captured, the comparison spec compares each pair with Playwright's
// own comparator. Both specs are generated in the run directory, never in the target repository.
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { locatePlaywright, NotInstalled, type Playwright } from '../../../../core/index.ts'
import { DriftError } from './compare.ts'
import { parseShots, parseShotsArgs, type ShotsConfig } from './config.ts'
import { decodePng, diffOf, encodePng, exactDiff, sizeOfPng, type Box } from './png.ts'
import { checkout, exec, interrupted, readJson, removeCheckout, runDirectory, stepper, targetOf, type Deps } from './run.ts'
import { startServer } from './server.ts'

/** The command that installs what `drift shots` needs, named in its error when it is missing. */
export const INSTALL_COMMAND = '/drift:install'

const PLACEHOLDER = '__PLAYWRIGHT_MODULE__'

export interface Pair {
  readonly route: string
  readonly width: number
  readonly verdict: 'identical' | 'differ'
  /** The differing pixels, as Playwright's comparator counts them. */
  readonly pixels?: number
  readonly box?: Box
  /** Both captures' sizes, when they differ. */
  readonly size?: { readonly base: readonly [number, number]; readonly head: readonly [number, number] }
  /** The diff image, relative to the run directory. */
  readonly diff?: string
}

export interface ShotsReport {
  readonly version: 1
  readonly verdict: 'identical' | 'differ'
  readonly differ: number
  readonly threshold: number
  readonly base: { readonly ref: string; readonly sha: string }
  readonly head: { readonly ref: string; readonly sha: string }
  readonly pairs: readonly Pair[]
  /** Requests to a host the config does not allow, aborted, on either side. */
  readonly blocked: readonly string[]
  /** Requests to an API host with no fixture, answered 404, on either side. */
  readonly unmocked: readonly string[]
}

/** The report as text: the verdict first, one line per pair, the requests left out, the refs last. */
export function renderShots(report: ShotsReport): string[] {
  const lines = [report.verdict === 'identical' ? 'drift: identical' : `drift: ${report.differ} differ`]
  for (const pair of report.pairs) {
    if (pair.verdict === 'identical') {
      lines.push(`${pair.route} @${pair.width}: identical`)
      continue
    }
    const box = pair.box === undefined ? '' : ` in ${pair.box.x},${pair.box.y},${pair.box.width},${pair.box.height}`
    const size = pair.size === undefined ? '' : ` (size ${pair.size.base.join('x')} → ${pair.size.head.join('x')})`
    lines.push(`${pair.route} @${pair.width}: ${pair.pixels ?? 0} px differ${box}${size}, diff ${pair.diff ?? 'none'}`)
  }
  if (report.threshold > 0) lines.push(`threshold ${report.threshold}: colour differences within it and pixels taken for anti-aliasing are not counted`)
  for (const url of report.blocked) lines.push(`blocked: ${url}`)
  for (const request of report.unmocked) lines.push(`unmocked: ${request}`)
  lines.push(`base ${report.base.sha.slice(0, 7)} (${report.base.ref}), head ${report.head.sha.slice(0, 7)} (${report.head.ref})`)
  return lines
}

/** A spec of this directory, its placeholder replaced by the install's module path, read as it is. */
export function generate(template: string, playwright: Pick<Playwright, 'module'>): string {
  const text = readFileSync(new URL(template, import.meta.url), 'utf8')
  return `// Generated by drift from ${template}: edit the template, never this copy.\n${text.replace(PLACEHOLDER, () => JSON.stringify(playwright.module))}`
}

/** A Playwright config running one spec of `dir` on one worker, its output under `results`. */
export function playwrightConfig(dir: string, spec: string, results: string, timeoutMs: number, snapshots?: string): string {
  return `module.exports = ${JSON.stringify({
    testDir: dir,
    testMatch: spec,
    outputDir: results,
    workers: 1,
    retries: 0,
    timeout: timeoutMs,
    reporter: [['list']],
    updateSnapshots: 'none',
    use: { headless: true },
    ...(snapshots === undefined ? {} : { snapshotPathTemplate: join(snapshots, '{arg}{ext}') }),
  }, null, 2)}\n`
}

/** The shared Playwright install, or a tool error naming the command that installs it. */
export function playwrightOf(deps: Pick<Deps, 'env' | 'home'>): Playwright {
  try {
    return locatePlaywright(deps.env, INSTALL_COMMAND, deps.home)
  } catch (error) {
    if (error instanceof NotInstalled) throw new DriftError(`${error.message}: run ${error.fix}`)
    throw error
  }
}

/** What every step of one `drift shots` run reads. */
interface Shooting {
  readonly top: string
  readonly config: ShotsConfig
  readonly run: string
  readonly spec: string
  readonly tree: string
  readonly playwright: Playwright
  readonly pairs: readonly string[]
  readonly signal: AbortSignal | undefined
}

const firstLine = (path: string): string | undefined => (existsSync(path) ? readFileSync(path, 'utf8').trim() : undefined)

/** Checks one side out, serves it, and captures every pair into `<run>/<side>`. */
async function shootSide(context: Shooting, side: 'base' | 'head', sha: string): Promise<void> {
  const { top, config, run, spec, tree, playwright, pairs, signal } = context
  const log = join(run, `${side}.log`)
  const step = stepper(side, log, signal)
  await checkout(step, top, sha, tree, config.install, config.env)
  let server
  try {
    server = await startServer({ argv: config.server, cwd: tree, env: config.env, port: config.port, url: config.url, startTimeoutMs: config.startTimeoutMs, log }, signal)
  } catch (error) {
    throw new DriftError(`${side}: ${error instanceof Error ? error.message : String(error)}`)
  }
  const out = join(run, side)
  try {
    mkdirSync(out)
    const plan = join(spec, `${side}.json`)
    writeFileSync(plan, `${JSON.stringify({
      url: config.url, routes: config.routes, viewports: config.viewports, fixtures: config.fixtures ?? null, api: config.api, allow: config.allow,
      ignore: config.ignore, now: config.now, fullPage: config.fullPage, timeoutMs: config.timeoutMs, out,
    }, null, 2)}\n`)
    const ran = await exec([process.execPath, playwright.cli, 'test', '--config', join(spec, 'capture.config.cjs')], spec, signal, log, { ...playwright.env, DRIFT_PLAN: plan, FORCE_COLOR: '0' })
    interrupted(signal)
    for (const pair of pairs) {
      const error = firstLine(join(out, `${pair}.error.txt`))
      if (error !== undefined) throw new DriftError(`${side}: ${pair} could not be captured: ${error}; its log: ${log}`)
    }
    if (ran.status !== 0 || pairs.some(pair => !existsSync(join(out, `${pair}.png`)))) throw new DriftError(`${side}: the capture failed (exit ${ran.status ?? 'none'}); its log: ${log}`)
  } finally {
    await server.stop()
  }
  await removeCheckout(top, tree)
}

/**
 * Compares every pair with Playwright's comparator, then reads each diff image it left. At
 * threshold 0, and for a pair whose sizes differ, the pair is compared byte for byte instead: the
 * comparator forgives pixels it takes for anti-aliasing, and paints no pixel of a size change.
 * Identical then means the same size and RGBA bytes, and the diff image is ours.
 */
async function compareSides(context: Shooting, threshold: number): Promise<Pair[]> {
  const { config, run, spec, playwright, pairs, signal } = context
  const log = join(run, 'compare.log')
  writeFileSync(log, '')
  const diff = join(run, 'diff')
  mkdirSync(diff)
  // Playwright files a snapshot under a name it rewrites past letters, digits and dashes: each base
  // capture is copied under its index.
  const snapshots = join(spec, 'snapshots')
  rmSync(snapshots, { recursive: true, force: true })
  mkdirSync(snapshots)
  pairs.forEach((pair, k) => copyFileSync(join(run, 'base', `${pair}.png`), join(snapshots, `shot-${k}.png`)))
  const plan = join(spec, 'compare.json')
  writeFileSync(plan, `${JSON.stringify({ pairs: pairs.map((pair, k) => ({ pair, snapshot: `shot-${k}` })), head: join(run, 'head'), diff, threshold }, null, 2)}\n`)
  const ran = await exec([process.execPath, playwright.cli, 'test', '--config', join(spec, 'compare.config.cjs')], spec, signal, log, { ...playwright.env, DRIFT_PLAN: plan, FORCE_COLOR: '0' })
  interrupted(signal)
  if (ran.status !== 0) throw new DriftError(`the comparison failed (exit ${ran.status ?? 'none'}); its log: ${log}`)
  const result: Pair[] = []
  let k = 0
  for (const route of config.routes) {
    for (const viewport of config.viewports) {
      const pair = pairs[k++] ?? ''
      const error = firstLine(join(diff, `${pair}.error.txt`))
      if (error !== undefined) throw new DriftError(`${pair} could not be compared: ${error}; its log: ${log}`)
      const image = join(diff, `${pair}.png`)
      const baseFile = readFileSync(join(run, 'base', `${pair}.png`))
      const headFile = readFileSync(join(run, 'head', `${pair}.png`))
      const base = sizeOfPng(baseFile)
      const head = sizeOfPng(headFile)
      const resized = base.width !== head.width || base.height !== head.height
      if (threshold === 0 || resized) {
        const exact = exactDiff(decodePng(baseFile), decodePng(headFile))
        if (exact.pixels === 0) {
          result.push({ route: route.path, width: viewport.width, verdict: 'identical' })
          continue
        }
        writeFileSync(image, encodePng(exact.image))
      } else if (!existsSync(image)) {
        result.push({ route: route.path, width: viewport.width, verdict: 'identical' })
        continue
      }
      const { pixels, box } = diffOf(readFileSync(image))
      result.push({
        route: route.path, width: viewport.width, verdict: 'differ', pixels, ...(box === undefined ? {} : { box }),
        ...(resized ? { size: { base: [base.width, base.height] as const, head: [head.width, head.height] as const } } : {}),
        diff: `diff/${pair}.png`,
      })
    }
  }
  return result
}

/** A capture's requests file, validated: its lists of strings, each empty when absent or malformed. */
export function requestsFileOf(raw: unknown): { blocked: string[]; unmocked: string[] } {
  const record = typeof raw === 'object' && raw !== null && !Array.isArray(raw) ? (raw as Record<string, unknown>) : {}
  const strings = (list: unknown): string[] => (Array.isArray(list) ? list.filter((item: unknown): item is string => typeof item === 'string') : [])
  return { blocked: strings(record['blocked']), unmocked: strings(record['unmocked']) }
}

/** The requests either side blocked or found no fixture for, each once, sorted. */
function requestsOf(run: string, pairs: readonly string[]): { blocked: string[]; unmocked: string[] } {
  const blocked = new Set<string>()
  const unmocked = new Set<string>()
  for (const side of ['base', 'head']) {
    for (const pair of pairs) {
      const record = requestsFileOf(readJson(join(run, side, `${pair}.requests.json`)))
      for (const url of record.blocked) blocked.add(url)
      for (const request of record.unmocked) unmocked.add(request)
    }
  }
  return { blocked: [...blocked].sort(), unmocked: [...unmocked].sort() }
}

/**
 * `drift shots`: captures both refs and compares them; 0 identical, 1 differ, and a tool error
 * (DriftError) when it cannot answer, the servers stopped and the checkouts removed either way.
 */
export async function shots(argv: readonly string[], deps: Deps): Promise<number> {
  const options = parseShotsArgs(argv)
  const playwright = playwrightOf(deps)
  const { top, configPath, baseSha, headSha } = await targetOf(options, deps)
  const config = parseShots(readJson(configPath), configPath)
  if (config.fixtures !== undefined && !(existsSync(config.fixtures) && statSync(config.fixtures).isDirectory())) {
    throw new DriftError(`${configPath}: "shots.fixtures" names no directory: ${config.fixtures}`)
  }
  const run = runDirectory(options.out, deps)
  const spec = join(run, 'spec')
  mkdirSync(spec, { recursive: true })
  const pageTimeout = config.timeoutMs * 4
  writeFileSync(join(spec, 'capture.spec.cjs'), generate('capture.pw.cjs', playwright))
  writeFileSync(join(spec, 'compare.spec.cjs'), generate('compare.pw.cjs', playwright))
  writeFileSync(join(spec, 'capture.config.cjs'), playwrightConfig(spec, 'capture.spec.cjs', join(spec, 'capture-results'), pageTimeout))
  writeFileSync(join(spec, 'compare.config.cjs'), playwrightConfig(spec, 'compare.spec.cjs', join(spec, 'compare-results'), pageTimeout, join(spec, 'snapshots')))
  const pairs = config.routes.flatMap(route => config.viewports.map(viewport => `${route.name}@${viewport.width}`))
  const work = mkdtempSync(join(deps.tmp, 'drift-work-'))
  const tree = join(work, 'tree')
  const context: Shooting = { top, config, run, spec, tree, playwright, pairs, signal: deps.signal }
  let compared: Pair[]
  try {
    for (const side of ['base', 'head'] as const) rmSync(join(run, side), { recursive: true, force: true })
    rmSync(join(run, 'diff'), { recursive: true, force: true })
    await shootSide(context, 'base', baseSha)
    await shootSide(context, 'head', headSha)
    compared = await compareSides(context, options.threshold)
  } finally {
    await removeCheckout(top, tree)
    rmSync(work, { recursive: true, force: true })
  }
  const differ = compared.filter(pair => pair.verdict === 'differ').length
  const report: ShotsReport = {
    version: 1,
    verdict: differ === 0 ? 'identical' : 'differ',
    differ,
    threshold: options.threshold,
    base: { ref: options.base, sha: baseSha },
    head: { ref: options.head, sha: headSha },
    pairs: compared,
    ...requestsOf(run, pairs),
  }
  const lines = renderShots(report)
  writeFileSync(join(run, 'report.json'), `${JSON.stringify(report, null, 2)}\n`)
  writeFileSync(join(run, 'report.txt'), `${lines.join('\n')}\n`)
  for (const line of lines) deps.out(line)
  deps.out(`out: ${run}`)
  return differ === 0 ? 0 : 1
}
